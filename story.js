export function recoveryStep(state, action) {
  if (action === 'screen') return { ...state, screenStopped: true };
  if (!state.screenStopped) return null;
  if (action === 'air') return { ...state, airOn: true };
  if (action === 'lock' && state.airOn) return { ...state, released: true };
  return null;
}

