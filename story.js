export function combineItems(a, b) {
  if (a === b) return null;
  const pair = [a, b].sort().join('+');
  if (pair === 'magnet+ruler') return 'magnetic-ruler';
  if (pair === 'card+lighter') return 'card-revealed';
  const pieces = { shard1: [1], shard2: [2], shard3: [3], plate12: [1, 2], plate23: [2, 3] };
  if (!pieces[a] || !pieces[b]) return null;
  const joined = [...pieces[a], ...pieces[b]];
  if (new Set(joined).size !== joined.length) return null;
  joined.sort(); if (joined.join('') === '13') return 'nofit'; // the outer pieces do not meet: the middle goes between them
  return joined.length === 3 ? 'plate' : 'plate' + joined.join('');
}
